#!/usr/bin/env python3
"""
mofa/scripts/project_pdbp.py

Projects preprocessed PDBP validation omic data into the trained PPMI MOFA factor space.
"""

import os
import argparse
import pandas as pd

try:
    from mofapy2.run.entry_point import entry_point
except ImportError:
    entry_point = None

def project_pdbp(model_path: str, input_dir: str, output_dir: str, cohort: str):
    """
    Loads the trained model, loads preprocessed aligned matrices,
    and runs the projection.
    """
    if entry_point is None:
        raise ImportError("mofapy2 is required for projection. Please ensure mofapy2 is installed.")
        
    os.makedirs(output_dir, exist_ok=True)
    
    # 1. Initialize projection
    ent = entry_point()
    ent.load_model(model_path)
    
    # 2. Load aligned views (features x samples)
    # The views are generated by preprocess_pdbp.py: {cohort}_{view}_aligned.csv
    views = ["RNA_seq", "CSF_Proteomics", "Plasma_Proteomics"]
    data_dict = {}
    
    for view in views:
        file_path = os.path.join(input_dir, f"{cohort.lower()}_{view.lower()}_aligned.csv")
        if os.path.exists(file_path):
            df = pd.read_csv(file_path, index_col=0)
            data_dict[view] = df
            print(f"Loaded {view} for projection: {df.shape}")
        else:
            print(f"Warning: Missing view {view} at {file_path}")
            
    if not data_dict:
        raise ValueError("No aligned view matrices found for projection in " + input_dir)
        
    # 3. Configure and run projection
    # mofapy2 expects a dict of dataframes (features x samples)
    ent.set_data_df(data_dict)
    
    # Use native missing data handling
    ent.set_data_options(scale_views=True)
    
    # Perform projection
    ent.run_projection()
    
    # 4. Extract Z (Latent factors)
    Z = ent.model.get_expectations('Z')
    
    # Get sample names from first available view
    first_view_df = next(iter(data_dict.values()))
    sample_names = list(first_view_df.columns)
    
    # Save Z per group (if multiple exist) or consolidated
    for group, z_matrix in Z.items():
        factor_names = [f"Factor{i+1}" for i in range(z_matrix.shape[1])]
        
        if len(sample_names) == z_matrix.shape[0]:
            df_z = pd.DataFrame(z_matrix, index=sample_names, columns=factor_names)
        else:
            df_z = pd.DataFrame(z_matrix, columns=factor_names)
            
        if len(Z) > 1:
            out_path = os.path.join(output_dir, f"{cohort.lower()}_latent_factors_{group}_Z.csv")
        else:
            out_path = os.path.join(output_dir, f"{cohort.lower()}_latent_factors_Z.csv")
            
        df_z.to_csv(out_path)
        print(f"Saved projected factors Z to: {out_path}")

def main():
    parser = argparse.ArgumentParser(description="Project PDBP data into PPMI MOFA space.")
    parser.add_argument("--model_path", required=True, help="Path to trained PPMI model.")
    parser.add_argument("--input_dir", required=True, help="Directory with _aligned.csv files.")
    parser.add_argument("--output_dir", required=True, help="Output directory.")
    parser.add_argument("--cohort", default="PDBP", help="Cohort name.")
    
    args = parser.parse_args()
    project_pdbp(args.model_path, args.input_dir, args.output_dir, args.cohort)

if __name__ == "__main__":
    main()
